// Generates THIRD_PARTY_LICENSES.md and src/settings/thirdParty.ts (shown in
// the About screen) from the dependencies that ship inside the app.
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const pkg = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8'));

// Packages bundled at runtime that are not direct dependencies.
const EXTRA = ['canvaskit-wasm', 'react-native-web', '@expo/vector-icons', 'expo-modules-core', 'react-native-screens'];
// Assets that are not npm packages.
const ASSETS = [
  { name: 'Material Design Icons (Pictogrammers)', version: '', license: 'Apache-2.0', url: 'https://pictogrammers.com' },
];
const FORBIDDEN = /(^|[^L])GPL|AGPL|SSPL|BUSL|Commercial/i;

const names = [...new Set([...Object.keys(pkg.dependencies ?? {}), ...EXTRA])].sort();
const rows = [];
for (const name of names) {
  const p = join(root, 'node_modules', name, 'package.json');
  if (!existsSync(p)) continue;
  const info = JSON.parse(readFileSync(p, 'utf8'));
  const license = typeof info.license === 'string' ? info.license : (info.license?.type ?? 'UNKNOWN');
  const url = typeof info.repository === 'string' ? info.repository : (info.repository?.url ?? info.homepage ?? '');
  rows.push({ name, version: info.version, license, url: url.replace(/^git\+/, '').replace(/\.git$/, '') });
}
rows.push(...ASSETS);

const bad = rows.filter((r) => FORBIDDEN.test(r.license) && !/LGPL/i.test(r.license));
if (bad.length > 0) {
  console.error('Dependencies with a license that is not allowed:', bad);
  process.exit(1);
}

const md = [
  '# Licencias de terceros / Third-party licenses',
  '',
  'Atril Musical se distribuye bajo la licencia MIT. Incluye los siguientes componentes de terceros, cada uno con su propia licencia.',
  '',
  'Atril Musical is distributed under the MIT License. It includes the following third-party components, each under its own license.',
  '',
  '| Componente / Component | Versión / Version | Licencia / License | Origen / Source |',
  '| --- | --- | --- | --- |',
  ...rows.map((r) => `| ${r.name} | ${r.version} | ${r.license} | ${r.url} |`),
  '',
  'Este archivo se genera con `npm run licenses`. / This file is generated with `npm run licenses`.',
  '',
].join('\n');
writeFileSync(join(root, 'THIRD_PARTY_LICENSES.md'), md);

const ts = [
  '// Copyright (c) 2026 Marcos Hernández Párraga. Licensed under the MIT License.',
  '// Generated by scripts/third-party-licenses.mjs (npm run licenses). Do not edit by hand.',
  '',
  'export const THIRD_PARTY: { name: string; license: string }[] = [',
  ...rows.map((r) => `  { name: ${JSON.stringify(r.name)}, license: ${JSON.stringify(r.license)} },`),
  '];',
  '',
].join('\n');
writeFileSync(join(root, 'src/settings/thirdParty.ts'), ts);
console.log(`[licenses] ${rows.length} components listed`);
